#!/usr/bin/env python3
"""One-off helper: extracts the handful of calligraphic glyph outlines the app
needs from LXGW WenKai TC Bold (SIL OFL 1.1) and writes ../glyphs.js.

The generated glyphs.js is committed, so this script is only needed if the
character set changes.

Usage:
  pip install fonttools brotli
  npm pack lxgw-wenkai-tc-webfont && tar xzf lxgw-wenkai-tc-webfont-*.tgz
  python3 scripts/extract-glyphs.py package/files lxgwwenkaitc-bold
"""
import glob, json, os, sys
from fontTools.ttLib import TTFont
from fontTools.pens.recordingPen import DecomposingRecordingPen

CHARS = "車馬象士將砲卒俥傌相仕帥炮兵楚河漢界軍死困斃勝紅黑和"

# The font has no glyph for the two red-side variants 俥 and 傌, so they are
# assembled from components of glyphs it does have: the 亻 radical of 偉 plus
# the right-hand 車 of 陣 / 馬 of 碼. Each entry is (source char, predicate on
# a contour's (xmin, xmax) in 1000-unit em coordinates).
COMPOSED = {
    "俥": [("偉", lambda x0, x1: x1 < 360), ("陣", lambda x0, x1: x0 >= 290)],
    "傌": [("偉", lambda x0, x1: x1 < 360), ("碼", lambda x0, x1: x0 >= 360)],
}


def contours(gs, name, k):
    """Glyph as a list of contours; each contour is a list of (op, points)."""
    rec = DecomposingRecordingPen(gs)
    gs[name].draw(rec)
    out, cur = [], []
    for op, pts in rec.value:
        pts = [(p[0] * k, p[1] * k) for p in pts]
        if op == "closePath":
            out.append(cur)
            cur = []
        elif op == "qCurveTo":
            # TrueType: implied on-curve points between off-curve points
            off, end = pts[:-1], pts[-1]
            for i, c in enumerate(off):
                nxt = end if i == len(off) - 1 else (
                    (c[0] + off[i + 1][0]) / 2, (c[1] + off[i + 1][1]) / 2)
                cur.append(("Q", [c, nxt]))
        else:
            cur.append(({"moveTo": "M", "lineTo": "L", "curveTo": "C"}[op], pts))
    return out


def xrange(contour):
    xs = [p[0] for _, pts in contour for p in pts]
    return min(xs), max(xs)


def main(files_dir, prefix):
    sources = set(CHARS) - set(COMPOSED) | {s for v in COMPOSED.values() for s, _ in v}
    need = set(sources)
    raw = {}
    for path in sorted(glob.glob(os.path.join(files_dir, prefix + "-subset-*.woff2"))):
        if not need:
            break
        font = TTFont(path)
        cmap = font.getBestCmap()
        gs = font.getGlyphSet()
        for ch in [c for c in need if ord(c) in cmap]:
            raw[ch] = contours(gs, cmap[ord(ch)], 1000.0 / font["head"].unitsPerEm)
            need.discard(ch)
    for ch, parts in COMPOSED.items():
        if all(s in raw for s, _ in parts):
            raw[ch] = [c for s, keep in parts for c in raw[s] if keep(*xrange(c))]
    need = set(CHARS) - set(raw)
    out = {}
    for ch in CHARS:
        if ch not in raw:
            continue
        pts = [p for c in raw[ch] for _, ps in c for p in ps]
        x0, x1 = min(p[0] for p in pts), max(p[0] for p in pts)
        y0, y1 = min(p[1] for p in pts), max(p[1] for p in pts)
        cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
        f = lambda p: "%d %d" % (round(p[0] - cx), round(cy - p[1]))
        d = "".join("".join(op + " ".join(f(p) for p in ps) for op, ps in c) + "Z"
                    for c in raw[ch])
        out[ch] = {"d": d, "w": round(x1 - x0), "h": round(y1 - y0)}
    if need:
        sys.exit("missing glyphs: " + "".join(need))
    body = ",\n".join("    %s: %s" % (json.dumps(ch, ensure_ascii=False),
                                      json.dumps(out[ch])) for ch in CHARS)
    js = """/*
 * Calligraphic glyph outlines used for pieces, river text and result banners.
 * Generated by scripts/extract-glyphs.py - do not edit by hand.
 *
 * Outlines are derived from LXGW WenKai TC Bold, Copyright (c) LXGW,
 * licensed under the SIL Open Font License 1.1 (see licenses/OFL.txt).
 * 俥 and 傌 are composed from components of other glyphs in that font.
 *
 * Each path is in a 1000-unit em, y pointing down, centred on its own
 * bounding box, so a glyph can be drawn centred on any point.
 */
(function (root) {
  'use strict';
  const GLYPHS = {
%s
  };
  if (typeof module !== 'undefined' && module.exports) module.exports = GLYPHS;
  else root.XQ_GLYPHS = GLYPHS;
})(typeof self !== 'undefined' ? self : this);
""" % body
    dest = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "glyphs.js")
    with open(dest, "w", encoding="utf-8") as fh:
        fh.write(js)
    print("wrote", dest, len(js), "bytes")

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
